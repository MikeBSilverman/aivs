@router.post("/orgs", status_code=status.HTTP_201_CREATED, response_model=OrganizationOut)
async def create_org(
    payload: OrganizationCreate, ctx: AuthenticatedContext, session: SessionDep
) -> Organization:
    """Enrol a member organisation. Hosting ISAC only.

    The organisation starts ``pending``: enrolment and activation are separate
    steps, so a half-finished onboarding cannot authenticate.
    """
    require(is_system_admin(ctx), "org_create_requires_system_admin")

    organization = Organization(
        slug=payload.slug,
        name=payload.name,
        org_type=payload.org_type,
        contact_email=payload.contact_email,
        status=OrgStatus.PENDING,
        stix_identity_id=f"identity--{uuid.uuid4()}",
    )
    session.add(organization)
    await record(
        session,
        action=AuditAction.ORG_CREATED,
        ctx=ctx,
        resource_type="organization",
        resource_id=payload.slug,
        details={"org_type": payload.org_type.value},
    )
    try:
        await session.commit()
    except IntegrityError as exc:
        await session.rollback()
        raise HTTPException(
            status.HTTP_409_CONFLICT, detail="An organisation with that slug already exists"
        ) from exc

    await session.refresh(organization)
    return organization


@router.get("/orgs", response_model=list[OrganizationOut])
async def list_orgs(ctx: AuthenticatedContext, session: SessionDep) -> list[Organization]:
    """List organisations. Hosting ISAC sees all; a member sees only itself."""
    query = select(Organization).order_by(Organization.slug)
    if not is_system_admin(ctx):
        query = query.where(Organization.id == ctx.org_id)
    return list((await session.execute(query)).scalars().all())


@router.post("/orgs/{org_id}/activate", response_model=OrganizationOut)
async def activate_org(
    org_id: uuid.UUID, ctx: AuthenticatedContext, session: SessionDep
) -> Organization:
    """Activate an enrolled organisation. Hosting ISAC only."""
    require(is_system_admin(ctx), "org_activate_requires_system_admin")

    organization = await session.get(Organization, org_id)
    if organization is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, detail="Organisation not found")

    previous = organization.status
    organization.status = OrgStatus.ACTIVE
    await record(
        session,
        action=AuditAction.ORG_STATUS_CHANGED,
        ctx=ctx,
        resource_type="organization",
        resource_id=str(org_id),
        details={"from": previous.value, "to": OrgStatus.ACTIVE.value},
    )
    await session.commit()
    await session.refresh(organization)
    return organization


@router.post("/orgs/{org_id}/suspend", response_model=OrganizationOut)
async def suspend_org(
    org_id: uuid.UUID, ctx: AuthenticatedContext, session: SessionDep
) -> Organization:
    """Suspend an organisation. Takes effect on their next request."""
    require(is_system_admin(ctx), "org_suspend_requires_system_admin")

    organization = await session.get(Organization, org_id)
    if organization is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, detail="Organisation not found")

    previous = organization.status
    organization.status = OrgStatus.SUSPENDED
    await record(
        session,
        action=AuditAction.ORG_STATUS_CHANGED,
        ctx=ctx,
        resource_type="organization",
        resource_id=str(org_id),
        details={"from": previous.value, "to": OrgStatus.SUSPENDED.value},
    )
    await session.commit()
    await session.refresh(organization)
    return organization


