"""Native API: organisation, certificate, and circle administration.

The hosting ISAC's operational surface: enrolling member firms, registering and
revoking their certificates, and running sharing circles.

Certificate handling here registers a *fingerprint*, never a key. Private keys
are generated by the member and never leave their infrastructure; the CA signs a
CSR out of band (``deploy/ca/issue-client.sh``) and what AIVS stores is the
SHA-256 of the resulting certificate. That means this endpoint cannot leak key
material because it never receives any.
"""

from __future__ import annotations

import datetime as dt
import uuid

from cryptography import x509
from cryptography.hazmat.primitives import hashes
from fastapi import APIRouter, HTTPException, status
from pydantic import BaseModel, ConfigDict, Field
from sqlalchemy import select
from sqlalchemy.exc import IntegrityError

from aivs_schemas.enums import CertStatus, OrgStatus
from aivs_schemas.models import (
    CircleCreate,
    CircleMemberAdd,
    CircleOut,
    OrganizationCreate,
    OrganizationOut,
)
from aivs_server.audit.log import AuditAction, record
from aivs_server.auth.deps import AuthenticatedContext, SessionDep, SettingsDep
from aivs_server.auth.policy import (
    can_administer_circle,
    can_manage_org,
    is_system_admin,
    require,
)
from aivs_server.auth.sessions import revoke_sessions_for_certificate
from aivs_server.db.models import (
    Circle,
    CircleMembership,
    ClientCertificate,
    Organization,
    TaxiiCollection,
)

__all__ = ["router"]

router = APIRouter(prefix="/api/v1", tags=["administration"])

#: Bound on a submitted certificate before parsing. A real certificate is a few
#: kilobytes; anything larger is misconfiguration or an attempt to spend our CPU
#: on ASN.1 parsing.
MAX_CERTIFICATE_PEM_BYTES = 16 * 1024


class CertificateRegister(BaseModel):
    """Register an already-issued client certificate for an organisation."""

    model_config = ConfigDict(extra="forbid")

    #: The issued certificate in PEM form. Public material only -- AIVS has no
    #: use for, and must never be sent, the corresponding private key.
    certificate_pem: str = Field(min_length=1, max_length=MAX_CERTIFICATE_PEM_BYTES)
    label: str | None = Field(default=None, max_length=120)


class CertificateOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    org_id: uuid.UUID
    fingerprint_sha256: str
    subject_dn: str
    not_before: dt.datetime
    not_after: dt.datetime
    status: CertStatus
    label: str | None


