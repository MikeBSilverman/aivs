@router.post(
    "/orgs/{org_id}/certificates",
    status_code=status.HTTP_201_CREATED,
    response_model=CertificateOut,
)
async def register_certificate(
    org_id: uuid.UUID,
    payload: CertificateRegister,
    ctx: AuthenticatedContext,
    session: SessionDep,
    settings: SettingsDep,
) -> ClientCertificate:
    """Register an issued certificate against an organisation.

    The fingerprint is computed here from the submitted certificate rather than
    accepted as a parameter: a caller-supplied fingerprint that did not match the
    certificate would bind an identity to material nobody holds.
    """
    require(can_manage_org(ctx, org_id), "certificate_register")

    organization = await session.get(Organization, org_id)
    if organization is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, detail="Organisation not found")

    try:
        certificate = x509.load_pem_x509_certificate(payload.certificate_pem.encode("utf-8"))
    except (ValueError, TypeError) as exc:
        raise HTTPException(
            status.HTTP_400_BAD_REQUEST, detail="Certificate could not be parsed"
        ) from exc

    if certificate.not_valid_after_utc <= dt.datetime.now(dt.UTC):
        raise HTTPException(status.HTTP_400_BAD_REQUEST, detail="Certificate has already expired")

    # The issuer must be the CA this instance trusts. Registration is what binds
    # a fingerprint to an organisation, so without this the application would
    # accept a self-signed certificate and rely entirely on the proxy refusing
    # it at handshake time -- making the proxy the single point of failure for
    # identity, which is exactly what auth/mtls.py declines to do elsewhere.
    expected_issuer = settings.expected_certificate_issuer_dn.strip()
    if expected_issuer and certificate.issuer.rfc4514_string() != expected_issuer:
        raise HTTPException(
            status.HTTP_400_BAD_REQUEST,
            detail="Certificate was not issued by this instance's certificate authority",
        )

    row = ClientCertificate(
        org_id=org_id,
        fingerprint_sha256=certificate.fingerprint(hashes.SHA256()).hex(),
        subject_dn=certificate.subject.rfc4514_string(),
        issuer_dn=certificate.issuer.rfc4514_string(),
        serial_hex=format(certificate.serial_number, "x"),
        not_before=certificate.not_valid_before_utc,
        not_after=certificate.not_valid_after_utc,
        status=CertStatus.ACTIVE,
        label=payload.label,
    )
    session.add(row)
    await record(
        session,
        action=AuditAction.CERT_REGISTERED,
        ctx=ctx,
        resource_type="organization",
        resource_id=str(org_id),
        details={"fingerprint": row.fingerprint_sha256, "subject": row.subject_dn},
    )
    try:
        await session.commit()
    except IntegrityError as exc:
        await session.rollback()
        raise HTTPException(
            status.HTTP_409_CONFLICT, detail="That certificate is already registered"
        ) from exc

    await session.refresh(row)
    return row


@router.post("/certificates/{certificate_id}/revoke", response_model=CertificateOut)
async def revoke_certificate(
    certificate_id: uuid.UUID, ctx: AuthenticatedContext, session: SessionDep
) -> ClientCertificate:
    """Revoke a certificate. Effective on the holder's very next request.

    Revocation is authoritative in this table rather than in a CRL, which is why
    the MVP needs no OCSP responder: the check is one indexed lookup on the
    authentication path.
    """
    row = await session.get(ClientCertificate, certificate_id)
    if row is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, detail="Certificate not found")

    require(can_manage_org(ctx, row.org_id), "certificate_revoke")

    if row.status is CertStatus.REVOKED:
        return row

    row.status = CertStatus.REVOKED
    row.revoked_at = dt.datetime.now(dt.UTC)
    row.revoked_reason = "revoked via API"

    # Revocation must lock out the humans using this certificate, not only the
    # machines. resolve_session would refuse them on their next request anyway;
    # ending them now means the audit trail shows the sessions closing at
    # revocation time rather than whenever each browser next happened to poll.
    closed = await revoke_sessions_for_certificate(session, fingerprint=row.fingerprint_sha256)
    await record(
        session,
        action=AuditAction.CERT_REVOKED,
        ctx=ctx,
        resource_type="certificate",
        resource_id=str(certificate_id),
        details={
            "fingerprint": row.fingerprint_sha256,
            "org_id": str(row.org_id),
            "portal_sessions_closed": closed,
        },
    )
    await session.commit()
    await session.refresh(row)
    return row


