@router.post("/circles", status_code=status.HTTP_201_CREATED, response_model=CircleOut)
async def create_circle(
    payload: CircleCreate, ctx: AuthenticatedContext, session: SessionDep
) -> Circle:
    """Create a sharing circle and its TAXII collection. Hosting ISAC only.

    The collection is created alongside the circle rather than as a separate
    step: a circle with no collection is invisible over TAXII, which is a
    confusing half-configured state for members to hit.
    """
    require(is_isac_editor(ctx), "circle_create_requires_isac_editor")

    circle = Circle(
        slug=payload.slug,
        name=payload.name,
        description=payload.description,
        minimum_tlp=payload.minimum_tlp,
        auto_member_org_types=[org_type.value for org_type in payload.auto_member_org_types],
    )
    session.add(circle)

    try:
        await session.flush()
    except IntegrityError as exc:
        await session.rollback()
        raise HTTPException(
            status.HTTP_409_CONFLICT, detail="A circle with that slug already exists"
        ) from exc

    session.add(
        TaxiiCollection(
            circle_id=circle.id,
            title=payload.name,
            description=payload.description,
            alias=payload.slug,
            can_read=True,
            # False until a TAXII write endpoint exists. There is no POST route
            # under the api root -- submissions go through /api/v1/submissions --
            # so advertising can_write led off-the-shelf TAXII clients to enable
            # their add-objects path and POST bundles that returned 405. The
            # member concludes the instance is broken; the ISAC concludes the
            # member never submitted. Better to advertise nothing than a door
            # that is not there.
            can_write=False,
        )
    )
    await record(
        session,
        action=AuditAction.CIRCLE_CREATED,
        ctx=ctx,
        resource_type="circle",
        resource_id=payload.slug,
        details={
            "minimum_tlp": payload.minimum_tlp.value,
            "auto_member_org_types": circle.auto_member_org_types,
        },
    )

    # Populate from the rule immediately, so a circle created with one is not
    # empty until the next organisation happens to be enrolled.
    await reconcile_circle(session, ctx, circle=circle)

    await session.commit()
    await session.refresh(circle)
    return circle


@router.get("/circles", response_model=list[CircleOut])
async def list_circles(ctx: AuthenticatedContext, session: SessionDep) -> list[Circle]:
    """List circles. The ISAC sees all; a member sees only those it belongs to.

    A member must not be able to enumerate the instance's full circle structure:
    which communities exist, and who is convening around what, is itself
    sensitive.
    """
    query = select(Circle).order_by(Circle.slug)
    if not is_isac_staff(ctx):
        query = query.where(Circle.id.in_(ctx.circle_ids))
    return list((await session.execute(query)).scalars().all())


@router.post("/circles/{circle_id}/members", status_code=status.HTTP_204_NO_CONTENT)
async def add_circle_member(
    circle_id: uuid.UUID,
    payload: CircleMemberAdd,
    ctx: AuthenticatedContext,
    session: SessionDep,
) -> None:
    """Add one or more organisations to a circle.

    Organisations already in the circle are skipped rather than refused:
    re-applying a roster is a normal operator action, and failing the batch on
    the one firm already present teaches people to add members one at a time.
    """
    require(can_administer_circle(ctx, circle_id), "circle_membership_manage")

    circle = await session.get(Circle, circle_id)
    if circle is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, detail="Circle not found")

    try:
        organisations = await resolve_organisations(
            session, org_ids=payload.org_ids, org_slugs=payload.org_slugs
        )
        await add_circle_members(
            session,
            ctx,
            circle=circle,
            organisations=organisations,
            role=payload.role,
            joined_at=payload.joined_at,
            now=dt.datetime.now(dt.UTC),
        )
        await session.commit()
    except CircleMembershipError as exc:
        await session.rollback()
        raise HTTPException(status.HTTP_404_NOT_FOUND, detail=str(exc)) from exc
    except IntegrityError as exc:
        await session.rollback()
        raise HTTPException(status.HTTP_409_CONFLICT, detail="Membership conflict") from exc


@router.delete("/circles/{circle_id}/members/{org_id}", status_code=status.HTTP_204_NO_CONTENT)
async def delete_circle_member(
    circle_id: uuid.UUID, org_id: uuid.UUID, ctx: AuthenticatedContext, session: SessionDep
) -> None:
    """Remove an organisation from a circle: closes its membership interval.

    Content they already collected is theirs; this stops future delivery. See
    ``services.circles.remove_circle_member``.
    """
    require(can_administer_circle(ctx, circle_id), "circle_membership_manage")

    closed = await remove_circle_member(
        session, ctx, circle_id=circle_id, org_id=org_id, now=dt.datetime.now(dt.UTC), via="api"
    )
    if not closed:
        raise HTTPException(status.HTTP_404_NOT_FOUND, detail="Membership not found")
    await session.commit()


