router = APIRouter(prefix="/api/v1", tags=["administration"])

#: Bound on a submitted certificate before parsing. A real certificate is a few
#: kilobytes; anything larger is misconfiguration or an attempt to spend our CPU
#: on ASN.1 parsing.
MAX_CERTIFICATE_PEM_BYTES = 16 * 1024


class CertificateRegister(BaseModel):
    """Register an already-issued client certificate for an organisation."""

    model_config = ConfigDict(extra="forbid")

    #: The issued certificate in PEM form. Public material only -- AIVS has no
    #: use for, and must never be sent, the corresponding private key.
    certificate_pem: str = Field(min_length=1, max_length=MAX_CERTIFICATE_PEM_BYTES)
    label: str | None = Field(default=None, max_length=120)


class CertificateOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    org_id: uuid.UUID
    fingerprint_sha256: str
    subject_dn: str
    not_before: dt.datetime
    not_after: dt.datetime
    status: CertStatus
    label: str | None


