class WebhookRegister(BaseModel):
    """Register a notification endpoint for the caller's own organisation."""

    model_config = ConfigDict(extra="forbid")

    url: str = Field(min_length=1, max_length=2000)
    #: Events to receive. Empty means all of them.
    #:
    #: One event exists today: ``submission.visible``, sent when content becomes
    #: readable by this organisation. It is deliberately contentless -- it names
    #: the submission and collection and nothing else, so the member polls TAXII
    #: to collect. See ``notify.events`` for why.
    events: list[str] = Field(default_factory=list, max_length=32)


class WebhookOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    org_id: uuid.UUID
    url: str
    events: list[str]
    is_active: bool
    consecutive_failures: int


class WebhookCreated(WebhookOut):
    """The registration response, carrying the signing secret.

    Returned **once**, at creation. It is stored only in encoded form, so a
    member who loses it registers a new webhook rather than recovering this one
    -- which is the correct trade for a value that authenticates our
    notifications to them.
    """

    signing_secret: str


@router.post("/webhooks", status_code=status.HTTP_201_CREATED, response_model=WebhookCreated)
async def register_webhook(
    payload: WebhookRegister,
    ctx: AuthenticatedContext,
    session: SessionDep,
    settings: SettingsDep,
) -> WebhookCreated:
    """Register a webhook for the caller's organisation.

    The URL is resolved and checked here, not only at delivery time, so a member
    finds out immediately that they have pointed it somewhere unreachable rather
    than discovering it from a silent absence of notifications.
    """
    require(can_manage_own_webhooks(ctx), "webhook_register")
    try:
        resolve_delivery_target(
            payload.url, allow_private=settings.dev_allow_private_webhook_targets
        )
    except WebhookRejectedError as exc:
        # Safe to return: it describes the caller's own configuration.
        raise HTTPException(
            status.HTTP_400_BAD_REQUEST,
            detail=f"That URL cannot be used as a webhook target ({exc.reason}).",
        ) from exc

    secret = secrets.token_urlsafe(32)
    # The identifier is generated here rather than left to the column default,
    # because the seal is bound to it: a column default is applied at INSERT,
    # so `webhook.id` would still be None at the point the secret is sealed.
    webhook_id = uuid.uuid4()
    webhook = Webhook(
        id=webhook_id,
        org_id=ctx.org_id,
        url=payload.url,
        hmac_secret_encrypted=SecretBox.from_settings(settings).seal(
            secret, purpose=SecretPurpose.WEBHOOK_HMAC, subject=webhook_id
        ),
        events=payload.events,
        is_active=True,
    )
    session.add(webhook)
    await record(
        session,
        action=AuditAction.WEBHOOK_CREATED,
        ctx=ctx,
        resource_type="webhook",
        details={"events": payload.events or ["*"]},
    )
    await session.commit()
    await session.refresh(webhook)

    return WebhookCreated(**WebhookOut.model_validate(webhook).model_dump(), signing_secret=secret)


@router.get("/webhooks", response_model=list[WebhookOut])
async def list_webhooks(ctx: AuthenticatedContext, session: SessionDep) -> list[Webhook]:
    """List the caller's own webhooks. Never another organisation's."""
    return list(
        (
            await session.execute(
                select(Webhook).where(Webhook.org_id == ctx.org_id).order_by(Webhook.created_at)
            )
        )
        .scalars()
        .all()
    )


@router.delete("/webhooks/{webhook_id}", status_code=status.HTTP_204_NO_CONTENT)
async def delete_webhook(
    webhook_id: uuid.UUID, ctx: AuthenticatedContext, session: SessionDep
) -> None:
    """Remove a webhook.

    Reported as absent when it belongs to another organisation, so identifiers
    cannot be probed to learn that someone else registered one. The role check
    comes first and does not depend on the id, so it is no oracle either.
    """
    require(can_manage_own_webhooks(ctx), "webhook_delete")
    webhook = await session.get(Webhook, webhook_id)
    if webhook is None or webhook.org_id != ctx.org_id:
        raise HTTPException(status.HTTP_404_NOT_FOUND, detail="Webhook not found")

    await session.delete(webhook)
    await record(
        session,
        action=AuditAction.WEBHOOK_DELETED,
        ctx=ctx,
        resource_type="webhook",
        resource_id=str(webhook_id),
    )
    await session.commit()


@router.post("/instance/distribution/pause", response_model=InstanceControlOut)
async def pause(
    payload: InstanceControlChange, ctx: AuthenticatedContext, session: SessionDep
) -> InstanceControlOut:
    """The stop button: refuse every publication and serve nothing until resumed."""
    require(can_pause_distribution(ctx), "pause_requires_isac_editor_or_system_admin")
    await pause_distribution(session, ctx, reason=payload.reason, now=dt.datetime.now(dt.UTC))
    await session.commit()
    return InstanceControlOut(distribution_paused=True)


@router.post("/instance/distribution/resume", response_model=InstanceControlOut)
async def resume(
    payload: InstanceControlChange, ctx: AuthenticatedContext, session: SessionDep
) -> InstanceControlOut:
    """Resume publication and serving. An ISAC editor only."""
    require(can_resume_distribution(ctx), "resume_requires_isac_editor")
    await resume_distribution(session, ctx, reason=payload.reason)
    await session.commit()
    return InstanceControlOut(distribution_paused=False)


@router.post("/orgs/{org_id}/quarantine", response_model=OrganizationOut)
async def quarantine(
    org_id: uuid.UUID, payload: QuarantineRequest, ctx: AuthenticatedContext, session: SessionDep
) -> Organization:
    """Cut an organisation off now: status, certificates and sessions. See services.quarantine."""
    require(can_quarantine_org(ctx, org_id), "quarantine")
    organisation = await load_org_for_update(session, org_id)
    if organisation is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, detail="Organisation not found")
    try:
        await quarantine_org(
            session,
            ctx,
            organisation=organisation,
            reason=payload.reason,
            now=dt.datetime.now(dt.UTC),
        )
    except QuarantineError as exc:
        raise HTTPException(status.HTTP_409_CONFLICT, detail=str(exc)) from exc
    await session.commit()
    await session.refresh(organisation)
    return organisation


@router.post("/orgs/{org_id}/reconnect", response_model=OrganizationOut)
async def reconnect(
    org_id: uuid.UUID, payload: ReconnectRequest, ctx: AuthenticatedContext, session: SessionDep
) -> Organization:
    """Return a quarantined organisation to service, on fresh credentials."""
    require(can_reconnect_org(ctx), "reconnect_requires_isac")
    organisation = await load_org_for_update(session, org_id)
    if organisation is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, detail="Organisation not found")
    try:
        await reconnect_org(
            session,
            ctx,
            organisation=organisation,
            backlog=payload.backlog,
            reason=payload.reason,
            now=dt.datetime.now(dt.UTC),
        )
    except QuarantineError as exc:
        raise HTTPException(status.HTTP_409_CONFLICT, detail=str(exc)) from exc
    await session.commit()
    await session.refresh(organisation)
    return organisation
