"""Native API: organisation, certificate, and circle administration.

The hosting ISAC's operational surface: enrolling member firms, registering and
revoking their certificates, and running sharing circles.

Certificate handling here registers a *fingerprint*, never a key. Private keys
are generated by the member and never leave their infrastructure; the CA signs a
CSR out of band (``deploy/ca/issue-client.sh``) and what AIVS stores is the
SHA-256 of the resulting certificate. That means this endpoint cannot leak key
material because it never receives any.
"""

