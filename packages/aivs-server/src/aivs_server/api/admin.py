@router.post("/circles", status_code=status.HTTP_201_CREATED, response_model=CircleOut)
async def create_circle(
    payload: CircleCreate, ctx: AuthenticatedContext, session: SessionDep
) -> Circle:
    """Create a sharing circle and its TAXII collection. Hosting ISAC only.

    The collection is created alongside the circle rather than as a separate
    step: a circle with no collection is invisible over TAXII, which is a
    confusing half-configured state for members to hit.
    """
    require(is_system_admin(ctx), "circle_create_requires_system_admin")

    circle = Circle(
        slug=payload.slug,
        name=payload.name,
        description=payload.description,
        minimum_tlp=payload.minimum_tlp,
    )
    session.add(circle)

    try:
        await session.flush()
    except IntegrityError as exc:
        await session.rollback()
        raise HTTPException(
            status.HTTP_409_CONFLICT, detail="A circle with that slug already exists"
        ) from exc

    session.add(
        TaxiiCollection(
            circle_id=circle.id,
            title=payload.name,
            description=payload.description,
            alias=payload.slug,
            can_read=True,
            can_write=True,
        )
    )
    await record(
        session,
        action=AuditAction.CIRCLE_CREATED,
        ctx=ctx,
        resource_type="circle",
        resource_id=payload.slug,
        details={"minimum_tlp": payload.minimum_tlp.value},
    )
    await session.commit()
    await session.refresh(circle)
    return circle


@router.get("/circles", response_model=list[CircleOut])
async def list_circles(ctx: AuthenticatedContext, session: SessionDep) -> list[Circle]:
    """List circles. The ISAC sees all; a member sees only those it belongs to.

    A member must not be able to enumerate the instance's full circle structure:
    which communities exist, and who is convening around what, is itself
    sensitive.
    """
    query = select(Circle).order_by(Circle.slug)
    if not is_system_admin(ctx):
        query = query.where(Circle.id.in_(ctx.circle_ids))
    return list((await session.execute(query)).scalars().all())


@router.post("/circles/{circle_id}/members", status_code=status.HTTP_204_NO_CONTENT)
async def add_circle_member(
    circle_id: uuid.UUID,
    payload: CircleMemberAdd,
    ctx: AuthenticatedContext,
    session: SessionDep,
) -> None:
    """Add an organisation to a circle."""
    require(can_administer_circle(ctx, circle_id), "circle_membership_manage")

    circle = await session.get(Circle, circle_id)
    if circle is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, detail="Circle not found")
    if await session.get(Organization, payload.org_id) is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, detail="Organisation not found")

    session.add(CircleMembership(circle_id=circle_id, org_id=payload.org_id, role=payload.role))
    await record(
        session,
        action=AuditAction.CIRCLE_MEMBER_ADDED,
        ctx=ctx,
        resource_type="circle",
        resource_id=str(circle_id),
        details={"org_id": str(payload.org_id), "role": payload.role.value},
    )
    try:
        await session.commit()
    except IntegrityError as exc:
        await session.rollback()
        raise HTTPException(
            status.HTTP_409_CONFLICT, detail="That organisation is already a member"
        ) from exc


@router.delete("/circles/{circle_id}/members/{org_id}", status_code=status.HTTP_204_NO_CONTENT)
async def remove_circle_member(
    circle_id: uuid.UUID, org_id: uuid.UUID, ctx: AuthenticatedContext, session: SessionDep
) -> None:
    """Remove an organisation from a circle.

    Content they already collected is theirs; this stops future delivery. The
    receipts recording what they did collect are untouched, because that record
    outlives the membership.
    """
    require(can_administer_circle(ctx, circle_id), "circle_membership_manage")

    membership = (
        await session.execute(
            select(CircleMembership).where(
                CircleMembership.circle_id == circle_id,
                CircleMembership.org_id == org_id,
            )
        )
    ).scalar_one_or_none()
    if membership is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, detail="Membership not found")

    await session.delete(membership)
    await record(
        session,
        action=AuditAction.CIRCLE_MEMBER_REMOVED,
        ctx=ctx,
        resource_type="circle",
        resource_id=str(circle_id),
        details={"org_id": str(org_id)},
    )
    await session.commit()
